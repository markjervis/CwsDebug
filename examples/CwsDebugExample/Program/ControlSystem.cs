// ============================================================================================
//  CwsDebug Example
//
//  A minimal SIMPL#Pro program that uses CwsDebug with a Crestron Construct (CH5) panel. It
//  controls a simple room on the "CwsDebugExample" Construct project:
//
//    Sources  five buttons in a Widget List; one is selected at a time (radio behaviour).
//    Volume   a slider; the program echoes its level back as feedback.
//    Power    a toggle; on or off, independent of the source selection.
//
//  CwsDebug features used:
//    - Logging at each level (Info, Notice, Warning, Fatal) and LogException in every handler,
//      so the program's activity can be followed on the debug page.
//    - RegisterContract, which lists the panel's signals in the Signals panel by contract name
//      (Main.Slider, Main.WidgetList.Items[1].Button, ...). From there a signal can be watched,
//      driven In (changes what the panel shows) or driven Out (simulates a press, running the
//      same handler as a real touch).
//
//  Requirements:
//    - The CwsDebug library project in this repository, referenced by CwsDebugExample.csproj;
//      .NET 8 on a 4-series processor or VC-4.
//    - The Construct project in ../Construct built, so its contract code and .cse2j exist in
//      its output folder (included prebuilt; see CwsDebugExample.csproj).
//    - A panel or XPanel at IP ID 03 running Construct/output/CwsDebugExample.ch5z.
//
//  Debug page:  https://<processor>/cws/example/debugger.html
//         VC-4: https://<server>/VirtualControl/Rooms/<roomId>/cws/example/debugger.html
// ============================================================================================

using Crestron.SimplSharp;                    // CrestronEnvironment (program start/stop events)
using Crestron.SimplSharpPro;                 // CrestronControlSystem, devices, signals
using Crestron.SimplSharpPro.UI;              // XpanelForHtml5, the panel class for CH5 projects
using CwsDebug;                               // CwsDebugPage: the debug page and its log

// The contract code is generated by Construct (Build) into the project's output folder and
// linked into this program by CwsDebugExample.csproj. Its namespace comes from the Construct project
// name. These aliases keep the names short below.
using Contract = CwsDebugExample.Contract;
using ItemEventArgs = CwsDebugExample.ItemEventArgs;   // a press on one item of a Widget List
using UIEventArgs = CwsDebugExample.UIEventArgs;       // a press or level from a single control

// Crestron's thread class, not .NET's: only Crestron's has MaxNumberOfUserThreads.
using Thread = Crestron.SimplSharpPro.CrestronThread.Thread;

namespace Example
{
    // Every SIMPL#Pro program has exactly one class that derives from CrestronControlSystem.
    // The processor creates it, calls the constructor, then calls InitializeSystem().
    public class ControlSystem : CrestronControlSystem
    {
        // ── Settings ─────────────────────────────────────────────────────────────────────────

        // Must match the IP ID set in the Construct project (Project Properties). The panel
        // connects to the processor at this ID.
        private const uint PanelIpId = 0x03;

        // The name the panel is given on the debug page. Any text works, but it must be the
        // same in RegisterContract (start-up) and UnregisterDevice (shut-down).
        private const string PanelName = "Panel";

        // The contract's runtime manifest, copied next to the program by CwsDebugExample.csproj.
        // CwsDebug reads it to show signals by their Construct names instead of join numbers.
        private const string ContractFile = "CwsDebugExample.cse2j";

        // The log gets a Warning entry when the volume rises past this percentage.
        private const int VolumeWarnPercent = 80;

        // Button labels. The panel's buttons have no text of their own: the program sends these
        // when the panel comes online (see RefreshPanel). Item 0 is the first button.
        private static readonly string[] SourceNames = { "Apple TV", "Laptop", "Cable", "Camera", "Blu-ray" };

        // ── Devices ──────────────────────────────────────────────────────────────────────────

        // The panel, and the contract that gives its controls names. Both are null if panel
        // registration fails, so every use below checks for null first.
        private readonly XpanelForHtml5? _panel;
        private readonly Contract? _contract;

        // ── Room state ───────────────────────────────────────────────────────────────────────

        // Events do not all arrive on one thread: panel presses come in on the panel's thread,
        // and a simulated press from the debug page comes in on a web-server thread. Two of them
        // at once could interleave and leave the state half-changed, so every read and change
        // of the three fields below happens inside lock (_stateLock).
        private readonly object _stateLock = new();
        private bool _powerOn;
        private int _source = -1;     // which SourceNames entry is selected; -1 means none
        private ushort _volume;       // 0 to 65535: an analog signal is always this range

        // ── Start-up ─────────────────────────────────────────────────────────────────────────

        // The constructor creates and registers devices. Keep it short: the processor waits for
        // it, and long work here delays the whole program starting.
        public ControlSystem() : base()
        {
            try
            {
                Thread.MaxNumberOfUserThreads = 20;

                // Ask to be told when the program stops, so the panel can be released cleanly.
                CrestronEnvironment.ProgramStatusEventHandler += OnProgramStatus;

                // Create the panel and register it with the processor. Registration can fail,
                // for example when another device already uses this IP ID.
                _panel = new XpanelForHtml5(PanelIpId, this);
                _panel.OnlineStatusChange += OnPanelOnlineChange;

                var result = _panel.Register();
                if (result != eDeviceRegistrationUnRegistrationResponse.Success)
                {
                    // Fatal: the program cannot work without its panel. LogFatal also writes
                    // to the processor's own error log.
                    CwsDebugPage.LogFatal("Panel registration failed: {0} ({1})", result, _panel.RegistrationFailureReason);
                    return;
                }
                CwsDebugPage.LogInfo("Panel registered at IP ID {0:X2}", PanelIpId);

                // The contract attaches to the panel. Each Construct page or widget is a smart
                // object, and each control on it is a join inside that object. The contract
                // hides those numbers: below, controls are reached by the names given in
                // Construct.
                _contract = new Contract(_panel);

                // Subscribe to the three controls. Each handler runs whenever that control is
                // used, on the panel or from the debug page's Signals panel.
                _contract.Main.WidgetList.Item.Button_PressEvent += OnSourcePress;   // any of the 5 buttons
                _contract.Main.Slider_LowerTouchEvent += OnVolumeChange;             // slider moved
                _contract.Main.Toggle_PressEvent += OnPowerPress;                    // toggle tapped
            }
            catch (Exception e)
            {
                // LogException writes the exception type, message and stack trace to the page.
                CwsDebugPage.LogException(e, "Error in the constructor");
            }
        }

        // InitializeSystem runs after the constructor. This is the place to start CwsDebug.
        public override void InitializeSystem()
        {
            try
            {
                // Start the debug page at /cws/example/. Logging works even before this line:
                // anything logged earlier (like the constructor's entries) is kept and shown.
                CwsDebugPage.Register("/example");

                // Put the panel in the Signals panel, named from the contract. After this, the
                // page can watch any control, and drive it: In changes what the panel shows,
                // Out simulates a press and runs the handlers in this file.
                if (_panel != null)
                    CwsDebugPage.RegisterContract(PanelName, _panel, ContractFile);

                // Notice is one step above Info: use it for things worth spotting in a busy log.
                CwsDebugPage.LogNotice("Example program started with {0} sources", SourceNames.Length);
            }
            catch (Exception e)
            {
                CwsDebugPage.LogException(e, "Error in InitializeSystem");
            }
        }

        // ── Panel online: send everything it should show ─────────────────────────────────────

        // A panel shows only what the program sends it. When it connects (or reconnects after a
        // network drop), send the whole state again so it never shows stale values.
        private void OnPanelOnlineChange(GenericBase device, OnlineOfflineEventArgs args)
        {
            if (!args.DeviceOnLine)
            {
                CwsDebugPage.LogWarning("Panel went offline");
                return;
            }
            CwsDebugPage.LogInfo("Panel online, sending labels and current state");
            lock (_stateLock) RefreshPanel();
        }

        // Sends the whole room state to the panel: how many source buttons to show, their labels,
        // which one is selected, the volume level and the power state. Every call here is a
        // signal going INTO the panel (feedback), so these appear as In rows on the debug page.
        // Called with _stateLock already held.
        private void RefreshPanel()
        {
            var main = _contract?.Main;
            if (main == null) return;

            // The Widget List gets its item count from the program (set in Construct with
            // "use contract for number of items"), so it shows nothing until this is sent.
            main.WidgetList.WidgetList_Set_Number_Of_Items((ushort)SourceNames.Length);

            for (ushort i = 0; i < SourceNames.Length; i++)
            {
                main.WidgetList.Item.Button_IndirectText(i, SourceNames[i]);   // the button's label
                main.WidgetList.Item.Button_Selected(i, i == _source);         // lit if it is the source
            }
            main.Slider_LowerTouchfb(_volume);   // where the slider should sit
            main.Toggle_Selected(_powerOn);      // whether the toggle shows on
        }

        // ── Sources: radio buttons ───────────────────────────────────────────────────────────

        // Runs for a press on any of the five source buttons. args.WidgetItemIndex says which
        // one (0 = first). A Pulse on the Out row of a Main.WidgetList.Items[n] button in the
        // debug page's Signals panel raises this event too.
        private void OnSourcePress(object? sender, ItemEventArgs args)
        {
            try
            {
                // A button sends true when pressed and false when released. Act on the press
                // only, or every tap would run this twice.
                if (!args.SigArgs.Sig.BoolValue) return;

                int index = args.WidgetItemIndex;
                if (index < 0 || index >= SourceNames.Length)
                {
                    CwsDebugPage.LogWarning("Source press from unknown item {0}", index);
                    return;
                }

                lock (_stateLock)
                {
                    // Sources and power are independent: choosing a source does not change power.
                    if (index == _source) return;   // already the source: nothing to change

                    var previous = _source;
                    _source = index;

                    // Radio behaviour: light the chosen button and turn every other one off.
                    for (ushort i = 0; i < SourceNames.Length; i++)
                        _contract?.Main.WidgetList.Item.Button_Selected(i, i == _source);

                    // Log the change as "from -> to", which reads well when scanning the log.
                    CwsDebugPage.LogInfo("Source: {0} -> {1}",
                        previous < 0 ? "none" : SourceNames[previous], SourceNames[_source]);
                }
            }
            catch (Exception e)
            {
                // A handler must never let an exception escape: log it and carry on.
                CwsDebugPage.LogException(e, "Handling a source press");
            }
        }

        // ── Volume: echo the slider's level back as feedback ─────────────────────────────────

        // Runs whenever the slider moves. The level arrives as 0 to 65535, whatever min and max
        // the slider shows in Construct, so it is converted to a percentage for the log.
        private void OnVolumeChange(object? sender, UIEventArgs args)
        {
            try
            {
                ushort level = args.SigArgs.Sig.UShortValue;
                int percent = (int)Math.Round(level * 100.0 / ushort.MaxValue);

                lock (_stateLock)
                {
                    if (level == _volume) return;   // no change: skip the log entry

                    int before = (int)Math.Round(_volume * 100.0 / ushort.MaxValue);
                    _volume = level;

                    // Send the level straight back. A CH5 slider shows its feedback value, so
                    // without this echo it springs back to where it was when you let go.
                    _contract?.Main.Slider_LowerTouchfb(level);

                    // Warn once, when the level crosses the threshold, not on every move above it.
                    if (percent > VolumeWarnPercent && before <= VolumeWarnPercent)
                        CwsDebugPage.LogWarning("Volume is high: {0}%", percent);
                }

                // A dragged slider sends many levels per second. These are Info entries, so the
                // page's level filter can hide them; raise CwsDebugPage.MinLevel to stop
                // recording them at all.
                CwsDebugPage.LogInfo("Volume {0}% (raw {1})", percent, level);
            }
            catch (Exception e)
            {
                CwsDebugPage.LogException(e, "Handling a volume change");
            }
        }

        // ── Power: toggle ────────────────────────────────────────────────────────────────────

        // Runs when the toggle is tapped. The program, not the toggle, decides the power state:
        // it flips _powerOn and sends the result back, so the panel always shows what the
        // program believes. Only the toggle's own feedback is sent; the source selection is
        // left as it is.
        private void OnPowerPress(object? sender, UIEventArgs args)
        {
            try
            {
                if (!args.SigArgs.Sig.BoolValue) return;   // act on press, not release

                bool on;
                lock (_stateLock)
                {
                    _powerOn = !_powerOn;
                    on = _powerOn;                         // read under the lock for the log line
                    _contract?.Main.Toggle_Selected(on);   // update the toggle only
                }
                CwsDebugPage.LogNotice("Power {0}", on ? "on" : "off");
            }
            catch (Exception e)
            {
                CwsDebugPage.LogException(e, "Handling the power toggle");
            }
        }

        // ── Shutdown ─────────────────────────────────────────────────────────────────────────

        // Runs when the program is stopping (a reload, or progreset). Release the panel here.
        private void OnProgramStatus(eProgramStatusEventType status)
        {
            if (status != eProgramStatusEventType.Stopping) return;

            // Order matters. Remove the panel from the debug page FIRST: this handler runs
            // before CwsDebug's own clean-up, so a browser polling the Signals panel could
            // otherwise reach a panel that has already been disposed.
            CwsDebugPage.UnregisterDevice(PanelName);

            if (_panel != null)
            {
                _panel.OnlineStatusChange -= OnPanelOnlineChange;
                _contract?.Dispose();
                _panel.Dispose();
            }
            // CwsDebug then stops its web page and saves the log to disk by itself.
        }
    }
}
